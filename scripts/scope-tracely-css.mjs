// Scopes Tracely's compiled stylesheet to the Traces tab, so its Tailwind classes work there
// without leaking into the rest of Parallax (Parallax has no Tailwind of its own).
//
// Usage: node scripts/scope-tracely-css.mjs <tracely-compiled.css> > app/tracely.css
// Get the input from a running Tracely dev server: the <link rel="stylesheet"> on /traces.
//
// - Every selector is nested under `.trc-scope`; html/body/:root rules apply to `.trc-scope` itself.
// - Tracely's own palette is dropped: its theme blocks are removed and every `rgb(var(--c-x) / a)`
//   becomes `rgb(from var(--trc-x) r g b / a)`. app/traces.css defines the `--trc-*` tokens (and
//   the canvas, shadow and font variables) from the active Parallax theme.
// - Keyframes get a `trc-` prefix (Parallax has its own `pulse`, `spin`, …).
// - Tracely's next/font faces are removed; the tab uses Parallax's fonts.
// - Elements Parallax styles globally start from browser defaults inside the scope (Tracely's
//   preflight assumes them), via `all: revert` placed before every Tracely rule, at the same
//   specificity as the preflight so the preflight still applies on top. (Not svg:
//   revert would also drop its fill/stroke presentation attributes.)
import { readFileSync } from "node:fs";
import postcss from "postcss";

const scope = ".trc-scope";
const reset = `
${scope} :where(a, button, code, h1, h2, h3, input, kbd, label, p, pre, select, table, td, textarea, th) { all: revert; }
`;

function scopeSelector(sel) {
  const s = sel.trim();
  if (s === ":root" || s === "html" || s === "body" || s === ":host")
    return scope;
  if (s.startsWith("[data-theme"))
    throw new Error(`Unexpected theme-scoped rule: ${s}`);
  if (/^(html|body)\b/.test(s)) return s.replace(/^(html|body)/, scope);
  if (s === "*") return `${scope}, ${scope} *`;
  return `${scope} ${s}`;
}

const input = readFileSync(process.argv[2], "utf8");
const root = postcss.parse(input);
const keyframes = new Set();
root.walkAtRules("keyframes", (rule) => keyframes.add(rule.params));
root.walkAtRules("font-face", (rule) => rule.remove());
// Tracely's dark and light theme blocks: Parallax's theme supplies these values instead.
root.walkRules((rule) => {
  if (rule.nodes?.some((d) => d.type === "decl" && d.prop === "--c-ink"))
    rule.remove();
});
root.walkRules((rule) => {
  if (rule.parent?.type === "atrule" && /keyframes$/.test(rule.parent.name))
    return;
  // next/font's generated `--font-*` holder classes
  if (/module__\w+__variable/.test(rule.selector)) return rule.remove();
  rule.selectors = [...new Set(rule.selectors.map(scopeSelector))];
});
root.walkAtRules("keyframes", (rule) => (rule.params = `trc-${rule.params}`));
root.walkDecls(/^animation(-name)?$/, (decl) => {
  decl.value = decl.value.replace(/[\w-]+/g, (word) =>
    keyframes.has(word) ? `trc-${word}` : word,
  );
});
root.walkDecls((decl) => {
  decl.value = decl.value.replace(
    /rgb\(var\(--c-([a-z0-9-]+)\)\s*\/\s*/g,
    "rgb(from var(--trc-$1) r g b / ",
  );
  if (decl.value.includes("--c-"))
    throw new Error(`Unmapped Tracely colour: ${decl.prop}: ${decl.value}`);
});
root.walkComments((c) => c.remove());
process.stdout.write(
  `/* Generated by scripts/scope-tracely-css.mjs from Tracely's compiled CSS. Do not edit. */\n${reset}\n${root.toString()}\n`,
);
